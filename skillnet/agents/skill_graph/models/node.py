class CodeSource(Enum):
    """
    Source of a code update.

    Identifies the source of a code change; different sources have different trust levels and handling logic:
    - LLM: LLM-generated code; requires execution validation (for stable skills)
    - REFACTOR: code generated by the refactor system; trusted update
    - OPTIMIZER: code repaired by the optimizer; trusted update
    - MANUAL: manually edited code; trusted update
    """
    LLM = "llm"
    REFACTOR = "refactor"
    OPTIMIZER = "optimizer"
    MANUAL = "manual"


@dataclass
class UpdateResult:
    """
    Result of a code update.

    Attributes:
        success: whether the update succeeded (i.e. whether code was written to node.code)
        reason: result reason code for programmatic dispatch
            - "code_unchanged": code identical; no update needed
            - "wrapper_redirect": wrapper protection; redirect to covered_by
            - "wrapper_architecture_violation": wrapper architecture violation (LLM attempted to override)
            - "wrapper_protected": wrapper is protected; force=True required
            - "stable_needs_verification": stable skill needs execution validation
            - "updated": update succeeded
        need_verification: whether execution validation is required to confirm the update
        allow_execution: whether execution is allowed (even when the update is rejected, execution validation may be permitted)
        redirect_to: for wrapper_redirect, the name of the skill that should be modified instead
        message: human-readable message for logs or hints
    """
    success: bool
    reason: str = ""
    need_verification: bool = False
    allow_execution: bool = True
    redirect_to: Optional[str] = None
    message: str = ""


@dataclass
class ConfirmResult:
    """
    Confirmation result after execution validation.

    Attributes:
        adopted: whether the pending code was adopted (written to node.code)
        message: human-readable message
    """
    adopted: bool
    message: str = ""


class SkillNode:
    """
    A node in the Skill Graph, representing one skill.

    Paper formula: s = (C_s, P_s, E_s, Children(s))

    Attributes:
        name: skill name (unique identifier)
        code: C_s - control flow, JavaScript async function
        parameters: P_s - parameter set
        preconditions: E_s^pre - preconditions
        expected_effects: E_s^post - expected effects
        children: Children(s) - list of child skills

    Paper-aligned aliases (via skill_network module):
        Skill = SkillNode
        Precondition = SkillPrecondition
        Effect = SkillEffect
    """

    def __init__(
        self,
        name: str,
        code: str = "",
        description: str = "",
        version: str = "1.0.0",
    ):
        self.name = name

        # Core identity
        self.code = code
        self.description = description

        # Extended attributes
        self.preconditions: List[SkillPrecondition] = []  # preconditions
        self.expected_effects: List[SkillEffect] = []  # expected effects
        self.actual_effects: List[ActualEffect] = []  # actual effects (state changes from each execution)
        self.versions: List[SkillVersion] = []  # version history
        self.statistics = SkillStatistics()  # statistics
        self.gradients = SkillGradients()  # gradient information

        # Graph structural info
        self.parents: List[str] = []  # list of parent skills that call this skill
        self.children: List[str] = []  # list of child skills called by this skill (in call order)
        self.in_degree: int = 0  # in-degree (number of skills calling this one)
        self.out_degree: int = 0  # out-degree (number of skills this one calls)

        # Optimization control
        self.stop_gradient: bool = False  # whether to stop gradient propagation (no optimization needed)

        # Parameterization support
        self.parameters: Dict[str, Dict[str, Any]] = {}  # parameter metadata
        # Format: {
        # "paramName": {
        # "type": "number|string|boolean|array",
        # "default": default_value,
        # "description": "parameter description",
        # "semantic": {  # full parameter semantics (v5.1+)
        # "quantity_semantic": "target_total|delta|none",
        # # - target_total: target total to be reached
        # # - delta: incremental quantity
        # # - none: non-quantity parameter
        # "direction": "input|output|config|bidirectional",
        # # - input: input material type (e.g. logType -> oak_log)
        # # - output: output product type (e.g. plankType -> oak_planks)
        # # - config: configuration parameter
        # # - bidirectional: context-dependent
        # "transform_hint": {...} | null,  # input-material mapping rules
        # "config_context": "fuel|log|tool|block" | null,
        # "is_fuel_param": bool,
        # "inferred_by": "parameter_extractor|llm|rule",
        # "confidence": 0.0-1.0
        # }
        # # Backward compatible: legacy format "semantic": "target_total|delta|config" still supported
        # }
        # }

        # Refactor/coverage-related fields
        self.is_covered: bool = False  # whether this skill is covered by another
        self.covered_by: Optional[str] = None  # which skill covers this one (the general skill's name)
        self.coverage_type: Optional['CoverageType'] = None  # coverage type enum
        self.is_general_skill: bool = False  # whether this is a general skill (used for sibling specialization cases)

        # Part 18: runtime-rollback fields
        self.refactor_failures: List[Dict[str, Any]] = []  # records failures after a refactor
        self.original_code_before_refactor: Optional[str] = None  # code before refactor (for rollback)

        # Deprecation: set when the Graph Planner produces a task-specific
        # composition with low reuse value (the node stays in the graph as
        # an audit trail; planner/effect-matcher/precondition-checker skip it).
        self.is_deprecated: bool = False
        self.deprecation_reason: Optional[str] = None
        self.deprecated_for_task: Optional[str] = None  # task it was deprecated for

        # Experimental skill fields (new skills that have failed but are not yet validated)
        self.is_experimental: bool = False  # whether this is an experimental skill (failed on first execution)
        self.first_failure_reason: Optional[str] = None  # first-failure reason
        self.experimental_retry_count: int = 0  # retry count for the experimental skill
        self.max_experimental_retries: int = 4  # maximum retries (aligned with action_agent_task_max_retries)
        self.experimental_task: Optional[str] = None  # task associated with the experimental skill

        # Experimental Skill lifecycle management fields (newly added)
        self.created_for_task: Optional[str] = None  # which task this skill was first created for
        self.is_verified: bool = False  # whether validated by a task (has completed a task successfully)

        # Task-specific skill marker (in-memory only; not persisted to code/ or vectordb)
        self.is_task_specific: bool = False

        # Gradual-deprecation fields (improved version)
        self.consecutive_failures: int = 0  # consecutive-failure count
        self.task_failures: Dict[str, int] = {}  # failure counts per task {task: count}
        self.deprecation_threshold: int = 3  # consecutive failures before deprecation (default 3)
        self.task_failure_threshold: int = 2  # failures on the same task before per-task deprecation (default 2)

        # Semantic confidence: grows with the number of execution samples; represents trust in preconditions and effects
        self.semantics_confidence: float = 0.0  # 0.0-1.0, computed from the number of execution samples

        # Value-function parameters (for planning and skill-update control)
        self.value_function_lambda: float = 1.0  # λ parameter, default 1.0
        self.value_function_alpha: float = 1.0  # α parameter, default 1.0
        self.value_function_beta: float = 1.0  # β parameter, default 1.0

        # Initialize version history
        if code or description:
            self.versions.append(SkillVersion(
                version=version,
                code=code,
                description=description,
                change_log="Initial version"
            ))

    @property
    def value_function(self) -> float:
        """
        Value function: V(s) = p_s - λ * u_s

        Where:
        - p_s is the Bayesian-smoothed success rate: p_s = (n_succ + α) / (n_succ + n_fail + α + β)
        - u_s is uncertainty: u_s = (n_s + 1)^(-1/2)
        - n_succ, n_fail, n_s are the success, failure, and total usage counts respectively

        Returns:
            float: the skill's value function value
        """
        n_succ = self.statistics.successful_executions
        n_fail = self.statistics.failed_executions
        n_s = self.statistics.total_executions

        # Bayesian-smoothed success rate
        alpha = self.value_function_alpha
        beta = self.value_function_beta
        p_s = (n_succ + alpha) / (n_succ + n_fail + alpha + beta) if (n_succ + n_fail + alpha + beta) > 0 else 0.0

        # Uncertainty
        u_s = math.pow(n_s + 1, -0.5)

        # Value function
        lambda_val = self.value_function_lambda
        v_s = p_s - lambda_val * u_s

        return v_s

    def add_precondition(self, precondition: SkillPrecondition):
        """Add a precondition."""
        self.preconditions.append(precondition)

    def add_effect(self, effect: SkillEffect):
        """Add an expected effect."""
        self.expected_effects.append(effect)

    def add_version(self, version: SkillVersion):
        """Add a new version."""
        self.versions.append(version)
        # Contract gate: only promote contract-valid versions to be "active" / retrievable.
        if getattr(version, "is_contract_valid", True):
            # Update current code and description to the latest version
            self.code = version.code
            self.description = version.description
        else:
            reason = ""
            try:
                if getattr(version, "contract_violations", None):
                    reason = f" violations={version.contract_violations[:2]}"
            except Exception:
                reason = ""
            print(f"\033[33m[Contract Gate] Version {version.version} for skill '{self.name}' is contract-invalid; not promoting to active code.{reason}\033[0m")

    def get_latest_version(self) -> Optional[SkillVersion]:
        """Get the latest version."""
        if self.versions:
            return self.versions[-1]
        return None

    def get_version(self, version: str) -> Optional[SkillVersion]:
        """Get a version by its version number."""
        for v in self.versions:
            if v.version == version:
                return v
        return None

    def add_execution_to_window(self, execution_id: str, success: bool, version: str = None):
        """
        Append an execution record to the current version's sliding window.

        Args:
            execution_id: execution ID
            success: whether the execution succeeded
            version: version number (uses the latest version when None)
        """
        if version is None:
            latest_version = self.get_latest_version()
            if latest_version:
                version = latest_version.version
            else:
                return

        version_obj = self.get_version(version)
        if not version_obj:
            return

        # Append execution record to the window
        version_obj.execution_window.append({
            "execution_id": execution_id,
            "success": success,
            "timestamp": datetime.now().isoformat(),
            "version": version,
        })

        # Keep the window size bounded
        window_size = version_obj.sliding_window_size
        if len(version_obj.execution_window) > window_size:
            version_obj.execution_window = version_obj.execution_window[-window_size:]

    def get_version_success_rate(self, version: str = None, use_window: bool = True) -> float:
        """
        Get the success rate for a specified version.

        Args:
            version: version number (uses the latest version when None)
            use_window: whether to use the sliding window (True) or all-time statistics (False)

        Returns:
            float: success rate
        """
        if version is None:
            latest_version = self.get_latest_version()
            if latest_version:
                version = latest_version.version
            else:
                return 0.0

        version_obj = self.get_version(version)
        if not version_obj:
            return 0.0

        if use_window and version_obj.execution_window:
            # Use the sliding window
            window = version_obj.execution_window
            if len(window) == 0:
                return 0.0
            successful = sum(1 for e in window if e.get("success", False))
            return successful / len(window)
        else:
            # Use all-time statistics (from statistics_snapshot)
            snapshot = version_obj.statistics_snapshot
            total = snapshot.get("total_executions", 0)
            if total == 0:
                return 0.0
            successful = snapshot.get("successful_executions", 0)
            return successful / total

    def check_performance_degradation(
        self,
        current_version: str = None,
        degradation_threshold: float = 0.15,
        min_window_size: int = 5,
    ) -> Tuple[bool, Optional[str], float, float]:
        """
        Check whether the current version has regressed relative to the previous one.

        Args:
            current_version: current version number (uses the latest version when None)
            degradation_threshold: regression threshold (default 0.15, i.e. 15%)
            min_window_size: minimum window size; need at least this many executions to detect

        Returns:
            Tuple[bool, Optional[str], float, float]:
                (degraded?, previous version, current-version success_rate, previous-version success_rate)
        """
        if current_version is None:
            latest_version = self.get_latest_version()
            if not latest_version:
                return False, None, 0.0, 0.0
            current_version = latest_version.version

        current_version_obj = self.get_version(current_version)
        if not current_version_obj:
            return False, None, 0.0, 0.0

        # Check window size
        if len(current_version_obj.execution_window) < min_window_size:
            return False, None, 0.0, 0.0

        # Get the previous version
        previous_version = current_version_obj.affected_subgraph.get("previous_version")
        if not previous_version:
            # If no record, try to find one in version history
            current_idx = None
            for i, v in enumerate(self.versions):
                if v.version == current_version:
                    current_idx = i
                    break
            if current_idx is not None and current_idx > 0:
                previous_version = self.versions[current_idx - 1].version
            else:
                return False, None, 0.0, 0.0

        previous_version_obj = self.get_version(previous_version)
        if not previous_version_obj:
            return False, None, 0.0, 0.0

        # Compute success rates for both versions
        current_sr = self.get_version_success_rate(current_version, use_window=True)
        previous_sr = self.get_version_success_rate(previous_version, use_window=False)

        # Check whether it has regressed
        degradation = previous_sr - current_sr
        is_degraded = degradation >= degradation_threshold

        return is_degraded, previous_version, current_sr, previous_sr

    def rollback_to_version(self, target_version: str) -> bool:
        """
        Roll back to a specified version.

        Args:
            target_version: target version number (e.g. "1.0.0")

        Returns:
            bool: whether the rollback succeeded
        """
        target_ver = self.get_version(target_version)
        if not target_ver:
            print(f"\033[31m[Rollback] Error: version '{target_version}' not found\033[0m")
            return False

        # Create a rollback version (based on the target version)
        current_version = self.get_latest_version()
        if current_version and current_version.version == target_version:
            print(f"\033[33m[Rollback] Already on version '{target_version}'; nothing to roll back\033[0m")
            return False

        # Determine the new version number (rollback version)
        if current_version:
            version_parts = current_version.version.split(".")
            version_parts[-1] = str(int(version_parts[-1]) + 1)
            rollback_version = ".".join(version_parts)
        else:
            rollback_version = target_version

        # Restore all attributes from the target version
        self.code = target_ver.code
        self.description = target_ver.description

        # Restore preconditions
        if target_ver.preconditions:
            self.preconditions = [copy.deepcopy(p) for p in target_ver.preconditions]

        # Restore effects
        if target_ver.effects:
            self.expected_effects = [copy.deepcopy(e) for e in target_ver.effects]

        # Restore parameters
        if target_ver.parameters:
            self.parameters = copy.deepcopy(target_ver.parameters)

        # Restore value-function parameters (if present in snapshot)
        if "value_function_lambda" in target_ver.statistics_snapshot:
            self.value_function_lambda = target_ver.statistics_snapshot.get("value_function_lambda", 1.0)
            self.value_function_alpha = target_ver.statistics_snapshot.get("value_function_alpha", 1.0)
            self.value_function_beta = target_ver.statistics_snapshot.get("value_function_beta", 1.0)

        # Create a rollback version record
        rollback_version_obj = SkillVersion(
            version=rollback_version,
            code=target_ver.code,
            description=target_ver.description,
            change_log=f"Rollback to version {target_version}",
            preconditions=[copy.deepcopy(p) for p in target_ver.preconditions] if target_ver.preconditions else [],
            effects=[copy.deepcopy(e) for e in target_ver.effects] if target_ver.effects else [],
            parameters=copy.deepcopy(target_ver.parameters) if target_ver.parameters else {},
            value_function=target_ver.value_function,
            statistics_snapshot=copy.deepcopy(target_ver.statistics_snapshot) if target_ver.statistics_snapshot else {},
            update_source="rollback",
            update_reason=f"Rollback from {current_version.version if current_version else 'unknown'} to {target_version}",
        )
        self.versions.append(rollback_version_obj)

        print(f"\033[32m[Rollback] Successfully rolled back to version '{target_version}'; created rollback version '{rollback_version}'\033[0m")
        return True

