    # Unified code-update interface
    # ═══════════════════════════════════════════════════════════════════════════

    def update_code(
        self,
        new_code: str,
        source: CodeSource,
        force: bool = False
    ) -> UpdateResult:
        """
        Unified entry point for code updates.

        All code modifications should go through this method to ensure:
        1. node.code is the single source of truth for the code
        2. The Wrapper architecture is protected
        3. Stable-skill updates require execution validation

        Rules (in priority order):
        1. Identical code → skip
        2. Wrapper architecture protection → block/redirect
        3. System source (REFACTOR/OPTIMIZER) → trusted update
        4. Experimental skill → free update
        5. Stable skill + LLM → deferred validation (adoption requires successful execution)

        Args:
            new_code: new code
            source: code source (CodeSource enum)
            force: whether to force an update (bypass wrapper protection)

        Returns:
            UpdateResult: the update result
        """
        # ═══════════════════════════════════════════════════════════════════
        # Rule 1: whether the code is identical
        # ═══════════════════════════════════════════════════════════════════
        if new_code.strip() == self.code.strip():
            return UpdateResult(success=True, reason="code_unchanged")

        # ═══════════════════════════════════════════════════════════════════
        # Rule 2: Wrapper architecture protection
        # ═══════════════════════════════════════════════════════════════════
        if self._should_protect_wrapper(new_code):
            covered_by = getattr(self, 'covered_by', 'unknown')

            if source == CodeSource.OPTIMIZER:
                # Redirect the optimization request to general_skill
                return UpdateResult(
                    success=False,
                    reason="wrapper_redirect",
                    redirect_to=covered_by,
                    message=f"This is a wrapper. Optimize {covered_by} instead."
                )
            elif source == CodeSource.LLM:
                # Allow execution validation but flag as rejected (will not be adopted)
                self._pending_code = new_code
                self._pending_source = source
                self._pending_rejected = True
                return UpdateResult(
                    success=False,
                    reason="wrapper_architecture_violation",
                    allow_execution=True,
                    message=f"Wrapper to {covered_by}. Full implementation may break architecture."
                )
            elif not force:
                return UpdateResult(
                    success=False,
                    reason="wrapper_protected",
                    message=f"Use force=True or modify {covered_by}"
                )

        # ═══════════════════════════════════════════════════════════════════
        # Rule 3: trusted system source (REFACTOR, OPTIMIZER) update
        # ═══════════════════════════════════════════════════════════════════
        if source in [CodeSource.REFACTOR, CodeSource.OPTIMIZER]:
            self._clear_pending()
            return self._do_update(new_code, source)

        # ═══════════════════════════════════════════════════════════════════
        # Rule 4: experimental skill may be freely updated
        # ═══════════════════════════════════════════════════════════════════
        if self.is_experimental:
            return self._do_update(new_code, source)

        # ═══════════════════════════════════════════════════════════════════
        # Rule 5: Stable skill + LLM → deferred validation
        # ═══════════════════════════════════════════════════════════════════
        self._pending_code = new_code
        self._pending_source = source
        return UpdateResult(
            success=False,
            reason="stable_needs_verification",
            need_verification=True,
            message="Stable skill requires execution verification before adopting new code."
        )

    def get_execution_code(self) -> str:
        """
        Return the code to use for execution.

        Returns pending code (if any), else the current code.
        This allows the new code to be used during execution validation without affecting node.code.

        Returns:
            str: code to use for execution
        """
        return getattr(self, '_pending_code', self.code)

    def has_pending_code(self) -> bool:
        """Check whether there is pending code."""
        return hasattr(self, '_pending_code')

    def confirm_pending(self, success: bool) -> ConfirmResult:
        """
        Confirm pending code after execution.

        Decides whether to adopt pending code based on execution result:
        - succeeded and not rejected → adopt the new code
        - failed or rejected → discard pending code; keep the original

        Args:
            success: whether execution succeeded

        Returns:
            ConfirmResult: confirmation result
        """
        if not hasattr(self, '_pending_code'):
            return ConfirmResult(adopted=False, message="no_pending")

        # Rejected updates are not adopted (wrapper architecture violations)
        if getattr(self, '_pending_rejected', False):
            covered_by = getattr(self, 'covered_by', 'unknown')
            message = f"Architecture violation rejected. Modify {covered_by} instead."
            self._clear_pending()
            return ConfirmResult(adopted=False, message=message)

        if success:
            pending_code = self._pending_code
            pending_source = getattr(self, '_pending_source', CodeSource.LLM)
            self._clear_pending()
            self._do_update(pending_code, pending_source)
            return ConfirmResult(adopted=True, message="New code adopted after successful execution.")
        else:
            self._clear_pending()
            return ConfirmResult(adopted=False, message="Execution failed. Original code preserved.")

    def _clear_pending(self) -> None:
        """Clear the pending state."""
        for attr in ['_pending_code', '_pending_source', '_pending_rejected']:
            if hasattr(self, attr):
                delattr(self, attr)

    def _do_update(self, code: str, source: CodeSource) -> UpdateResult:
        """
        Apply the actual update.

        Directly updates node.code and records the update source.

        Args:
            code: new code
            source: code source

        Returns:
            UpdateResult: update-success result
        """
        self.code = code
        self._last_update_source = source
        return UpdateResult(success=True, reason="updated")

    def _should_protect_wrapper(self, new_code: str) -> bool:
        """
        Decide whether wrapper architecture should be protected.

        Protection is triggered only when the following conditions hold:
        1. The node is marked is_covered (set by refactor)
        2. The new code no longer calls the function indicated by covered_by

        Meaning:
        - If the new code still calls covered_by → allow update (possibly a wrapper fix)
        - If the new code no longer calls covered_by → block (possibly a full re-implementation overriding the wrapper)

        Args:
            new_code: new code

        Returns:
            bool: whether the wrapper should be protected
        """
        if not getattr(self, 'is_covered', False):
            return False

        covered_by = getattr(self, 'covered_by', None)
        if not covered_by:
            return False

        # Check whether the new code still calls covered_by
        # Match function-call pattern via regex: functionName(
        call_pattern = rf'\b{re.escape(covered_by)}\s*\('

        # Still calls → no protection (allow wrapper fixes)
        # No longer calls → protect (block architecture-breaking change)
        return not bool(re.search(call_pattern, new_code))

    @classmethod
    def _migrate_parameters(cls, parameters: Dict[str, Any]) -> Dict[str, Any]:
        """
        Migrate old parameter metadata to ensure compatibility with v5.1+ format.

        Migrations performed:
        1. Array parameters: Add supported_values if missing
        2. Semantic format: Convert old string format to new dict format

        Args:
            parameters: Parameter metadata dictionary

        Returns:
            Migrated parameter metadata
        """
        if not parameters:
            return parameters

        for param_name, param_info in parameters.items():
            if isinstance(param_info, dict):
                param_type = param_info.get("type")
                default = param_info.get("default")

                # Migration 1: Array parameters need supported_values
                if param_type == "array" and isinstance(default, list) and default:
                    if "supported_values" not in param_info:
                        param_info["supported_values"] = default

                # Migration 2: Convert old string semantic to new dict format
                semantic = param_info.get("semantic")
                if isinstance(semantic, str):
                    # Old format: "target_total" | "delta" | "config"
                    # New format: {"quantity_semantic": "...", "direction": "...", ...}
                    old_to_quantity = {
                        "target_total": "target_total",
                        "delta": "delta",
                        "config": "none",
                    }
                    quantity_semantic = old_to_quantity.get(semantic, "none")

                    # Infer direction from param name
                    param_lower = param_name.lower()
                    if "type" in param_lower and semantic != "config":
                        direction = "bidirectional"  # Need context to determine
                    else:
                        direction = "config"

                    param_info["semantic"] = {
                        "quantity_semantic": quantity_semantic,
                        "direction": direction,
                        "inferred_by": "legacy_migration",
                        "confidence": 0.5,
                    }

        return parameters

