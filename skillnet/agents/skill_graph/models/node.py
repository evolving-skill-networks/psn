"""
SkillNode dataclass

A node in the Skill Graph, representing one skill.

Aligned with the paper "Evolving Programmatic Skill Networks":

    s = (C_s, P_s, E_s, Children(s))

where:
    C_s = code         control flow (JavaScript code)
    P_s = parameters   parameter set
    E_s = (preconditions, expected_effects)  preconditions / postconditions
    Children(s) = children  list of child skills

Value Function（Section 2.2）：
    V(s) = p̂_s - u_s

where p̂_s is the Laplace-smoothed success rate and u_s is the uncertainty.
"""

