    def mark_execution_failed(self, task: str = None, error: str = None) -> Dict[str, Any]:
        """
        Mark one failed execution: only increment counters and return whether deletion is warranted.

        Phase 9 refactor: do not set is_deprecated directly; let on_task_completed() handle removal centrally.

        Args:
            task: associated task (optional)
            error: error message (optional)

        Returns:
            Dict[str, Any]: contains state info and a should_deprecate flag
            - should_deprecate: whether the deletion threshold is reached (caller decides whether to delete)
            - deprecation_reason: deletion reason (when should_deprecate=True)
        """
        result = {
            "was_deprecated": self.is_deprecated,
            "now_deprecated": self.is_deprecated,  # Phase 9: no longer mutated here
            "consecutive_failures": 0,
            "task_failures": 0,
            "should_deprecate": False,  # Phase 9: new; caller decides whether to delete
            "deprecation_reason": None,
            "experimental_retry_count": 0,
            "experimental_exceeded_retries": False,
            # Legacy field compatibility
            "deprecation_triggered": False,
            "reason": None,
        }

        # Increment the consecutive-failure count
        self.consecutive_failures += 1
        result["consecutive_failures"] = self.consecutive_failures

        # Record the first-failure reason
        if self.consecutive_failures == 1 and error:
            self.first_failure_reason = error

        # If associated with a task, increment the per-task failure count
        if task:
            self.task_failures[task] = self.task_failures.get(task, 0) + 1
            result["task_failures"] = self.task_failures[task]

        # ========== Experimental Skill lifecycle management ==========
        if self.is_experimental:
            # Check whether this is a retry of the same task
            if self.experimental_task and task and self.experimental_task != task:
                # Different task; do not increment (experimental state continues)
                pass
            else:
                self.experimental_retry_count += 1
                if not self.experimental_task:
                    self.experimental_task = task

            result["experimental_retry_count"] = self.experimental_retry_count

            # Check whether max retries was exceeded
            if self.experimental_retry_count >= self.max_experimental_retries:
                # Phase 9: do not set is_deprecated directly; only return the flag
                deprecation_reason = (
                    f"Experimental skill exceeded max retries ({self.experimental_retry_count}/{self.max_experimental_retries})"
                )
                if self.first_failure_reason:
                    deprecation_reason += f". First failure reason: {self.first_failure_reason[:100]}"

                result["experimental_exceeded_retries"] = True
                result["should_deprecate"] = True
                result["deprecation_reason"] = deprecation_reason
                # Legacy field compatibility
                result["deprecation_triggered"] = True
                result["reason"] = deprecation_reason

                print(f"\033[33m[Experimental Skill] Reached deletion threshold ({self.experimental_retry_count}/{self.max_experimental_retries}); awaiting on_task_completed for removal\033[0m")
                return result

        # ========== Normal deprecation logic ==========
        should_deprecate = False
        deprecation_reason = None

        # Strategy 1: consecutive failures exceed the threshold
        if self.consecutive_failures >= self.deprecation_threshold:
            should_deprecate = True
            deprecation_reason = f"Consecutive failures: {self.consecutive_failures} (threshold: {self.deprecation_threshold})"
            if error:
                deprecation_reason += f"; last error: {error[:100]}"

        # Strategy 2: same-task failures exceed the threshold
        if task and self.task_failures.get(task, 0) >= self.task_failure_threshold:
            should_deprecate = True
            task_fail_count = self.task_failures[task]
            if deprecation_reason:
                deprecation_reason += f"; task '{task}' failed {task_fail_count} times"
            else:
                deprecation_reason = f"Task '{task}' failed {task_fail_count} times (threshold: {self.task_failure_threshold})"

        # Phase 9: do not set is_deprecated directly; only return the flag
        if should_deprecate:
            result["should_deprecate"] = True
            result["deprecation_reason"] = deprecation_reason
            # Legacy field compatibility
            result["deprecation_triggered"] = True
            result["reason"] = deprecation_reason

        return result

    def mark_execution_success(self, task: str = None) -> Dict[str, Any]:
        """
        Mark one successful execution; may restore a deprecated skill.

        Args:
            task: associated task (optional)

        Returns:
            Dict[str, Any]: information about deprecation-state changes
            - should_trigger_refactor: [Fix 7] if an experimental skill succeeds for the first time, trigger the delayed refactor
        """
        result = {
            "was_deprecated": self.is_deprecated,
            "now_deprecated": False,
            "reactivated": False,
            "consecutive_failures_reset": self.consecutive_failures > 0,
            "was_experimental": self.is_experimental,
            "now_experimental": False,
            "experimental_verified": False,
            "should_trigger_refactor": False,  # [Fix 7] delayed-refactor trigger flag
        }

        # Reset consecutive-failure count
        self.consecutive_failures = 0

        # If associated with a task, decrement the per-task failure count (but not below 0)
        if task and task in self.task_failures:
            self.task_failures[task] = max(0, self.task_failures[task] - 1)
            # If the task's failure count drops to 0, remove it from the dict
            if self.task_failures[task] == 0:
                del self.task_failures[task]

        # If previously deprecated and now succeeded, consider restoration
        if self.is_deprecated:
            # Restoration condition: consecutive successful executions (success resets consecutive failures)
            self.is_deprecated = False
            self.deprecation_reason = None
            self.deprecated_for_task = None
            result["reactivated"] = True

        # If it was experimental and now succeeded, clear the flag and trigger the delayed refactor
        if self.is_experimental:
            self.is_experimental = False
            self.is_verified = True  # mark as validated
            self.first_failure_reason = None
            self.experimental_retry_count = 0
            self.experimental_task = None
            result["experimental_verified"] = True
            result["should_trigger_refactor"] = True  # [Fix 7] inform the caller to trigger the delayed refactor
            print(f"\033[32m[Experimental Skill] Successfully validated! is_verified=True; delayed refactor will be triggered\033[0m")

        result["now_deprecated"] = self.is_deprecated
        result["now_experimental"] = self.is_experimental
        return result



